function importMyInventory(replaceAll) {
  const now = new Date().toISOString();
  const beans = MyInventoryData.map(function(item, idx) {
    return {
      id: 'bean_' + Date.now().toString(36) + '_' + idx,
      brand: item.brand,
      colorCode: item.colorCode,
      colorName: item.colorName,
      stock: item.stock,
      lowStockThreshold: item.lowStockThreshold,
      reserved: 0,
      note: item.note,
      createdAt: now,
      updatedAt: now
    };
  });

  if (replaceAll) {
    localStorage.setItem('pdb_beans', JSON.stringify(beans));
  } else {
    const existing = JSON.parse(localStorage.getItem('pdb_beans') || '[]');
    // 按 brand + colorCode 去重，新数据覆盖旧数据
    const map = {};
    existing.forEach(function(b) {
      map[b.brand + '_' + b.colorCode] = b;
    });
    beans.forEach(function(b) {
      map[b.brand + '_' + b.colorCode] = b;
    });
    localStorage.setItem('pdb_beans', JSON.stringify(Object.values(map)));
  }

  // 同时添加一条导入记录到库存记录
  var records = JSON.parse(localStorage.getItem('pdb_records') || '[]');
  records.unshift({
    id: 'rec_' + Date.now().toString(36),
    type: '导入',
    beanId: '',
    brand: '系统',
    colorCode: '',
    colorName: '',
    delta: 0,
    before: 0,
    after: 0,
    note: '从Excel导入库存数据，共' + beans.length + '条色号',
    time: now
  });
  localStorage.setItem('pdb_records', JSON.stringify(records));

  console.log('已导入 ' + beans.length + ' 条库存数据');
  if (typeof UI !== 'undefined') {
    UI.toast('已导入 ' + beans.length + ' 条库存数据', 'success');
  }
  if (typeof App !== 'undefined') {
    App.updateNavCounts();
    if (App.getCurrentPage) {
      var page = App.getCurrentPage();
      if (page === 'beans' || page === 'home' || page === 'records') {
        App.navigate(page);
      }
    }
  }
  return beans.length;
}

